//scalar types
fn main() 
{
    let e = 100;
    let x :u32 = 100; //int literal
    let y:i32= -100;
    let z = 3.0;
    let a : f32 = 2.0; //float literal
    let f = true;
    let b : bool = false; //boolean literal
    let c = 'z';
    let d:char = 'f'; //character literal 
    println!("{e}");
    println!("{x}");
    println!("{y}");
    println!("{z}");
    println!("{a}");
    println!("{f}");
    println!("{b}");
    println!("{c}");
    println!("{d}");
}